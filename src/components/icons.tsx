export type IconKey = keyof typeof ICONS

export function isIconKey(v: unknown): v is IconKey {
  return typeof v === 'string' && v in ICONS
}

export function Icon({
  name,
  size = 16,
  className,
  style,
  strokeWidth = 1.75,
}: {
  name: IconKey | string | undefined
  size?: number
  className?: string
  style?: React.CSSProperties
  strokeWidth?: number
}) {
  const Cmp = (isIconKey(name) ? ICONS[name] : ICONS.unknown) as React.ComponentType<any>
  return (
    <Cmp size={size} className={className} style={style} strokeWidth={strokeWidth} aria-hidden />
  )
}

