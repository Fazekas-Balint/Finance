export function normalizeIcon(value: unknown, fallback: IconKey = 'package'): IconKey {
  if (isIconKey(value)) return value
  if (typeof value === 'string' && EMOJI_TO_KEY[value]) return EMOJI_TO_KEY[value]
  return fallback
}
